NO_CONTEXT = "(ไม่พบเอกสารกฎหมายหรือคู่มือที่เกี่ยวข้องเพิ่มเติม)"


def format_legal_context(chunks: list[Document]) -> str:
    """
    The retrieved corpus passages, labelled by source and page.

    Labelled in prose rather than as [1] [2]: a numbered list here is an invitation to
    cite those numbers in the answer, and the reference letters carry no bracketed
    citations at all.
    """
    if not chunks:
        return NO_CONTEXT

    return "\n\n".join(
        f"จาก {chunk.metadata['source']} หน้า {chunk.metadata['page']}\n{chunk.page_content}"
        for chunk in chunks
    )


def build_messages(request: AnalysisRequest, legal_chunks: list[Document]) -> list[tuple[str, str]]:
    """Assemble the CRAFT context block (C) and pair it with the standing prompt."""
    human = (
        f"[ข้อมูลโครงการ]\n{format_project(request)}\n\n"
        f"[สรุปจำนวนแหล่งที่ตรวจพบจากฐานข้อมูล สผ.]\n{format_category_context(request)}\n\n"
        f"[รายละเอียดแหล่งที่ได้รับผลกระทบ]\n{format_sites(request)}\n\n"
        f"[แนวทางที่ ONEP ส่งมาประกอบ]\n{format_guidance_context(request)}\n\n"
        f"[เอกสารกฎหมายและคู่มือที่อาจเกี่ยวข้อง]\n{format_legal_context(legal_chunks)}"
    )

    return [("system", SYSTEM_PROMPT), ("human", human)]
